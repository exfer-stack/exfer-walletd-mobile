const DICT: Record<Lang, Record<MsgKey, string>> = { en: EN, zh: ZH };

type Vars = Record<string, string | number>;
function interpolate(s: string, vars?: Vars): string {
  // Guard a missing key (e.g. a consent titleKey with no string yet) so the UI
  // shows the English fallback the caller passed, never "undefined".
  if (s == null) return "";
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : s;
}

interface I18n {
  lang: Lang;
  t: (key: MsgKey, vars?: Vars) => string;
}

const I18nCtx = createContext<I18n>({
  lang: "en",
  t: (key) => EN[key],
});

export function I18nProvider({
  lang,
  children,
}: {
  lang: Lang;
  children: ReactNode;
}) {
  const table = DICT[lang] ?? EN;
  const t = (key: MsgKey, vars?: Vars) =>
    interpolate(table[key] ?? EN[key], vars);
  return <I18nCtx.Provider value={{ lang, t }}>{children}</I18nCtx.Provider>;
}

export function useT(): I18n {
  return useContext(I18nCtx);
}

/** Translate outside React (e.g. in error helpers). Reads the persisted lang. */
export function tStatic(key: MsgKey, vars?: Vars): string {
  const table = DICT[readLang()] ?? EN;
  return interpolate(table[key] ?? EN[key], vars);
}

/** A short, localized relative time ("just now" / "3m ago" / "2h ago" / "5d ago")
 *  for the conversations list. Coarse on purpose — exact timestamps aren't useful
 *  in a chat picker. */
export function relativeTime(ts: number, lang: Lang): string {
  const t = (key: MsgKey, vars?: Vars) => interpolate((DICT[lang] ?? EN)[key] ?? EN[key], vars);
  const diff = Math.max(0, Date.now() - ts);
  const min = Math.floor(diff / 60000);
  if (min < 1) return t("agent.time.now");
  if (min < 60) return t("agent.time.min", { n: min });
  const hr = Math.floor(min / 60);
  if (hr < 24) return t("agent.time.hour", { n: hr });
  return t("agent.time.day", { n: Math.floor(hr / 24) });
}
