const LS_KEY = "exfer-mobile-lang";
export function readLang(): Lang {
  try {
    return localStorage.getItem(LS_KEY) === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}
export function persistLang(l: Lang) {
  try {
    localStorage.setItem(LS_KEY, l);
  } catch {
    /* ignore */
  }
}

